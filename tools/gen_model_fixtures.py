#!/usr/bin/env python3
"""Generate torch-f64 goldens + tiny safetensors weights for Rust model parity.

Drives the VERBATIM upstream muscriptor modules (lm.py, transformer.py,
conditioners.py from a local upstream checkout) at tiny dims and
exports:

  crates/mtab-core/tests/fixtures/model/
    tiny.fixture               randomly initialized test tensors (not pretrained weights)
    wav.f32                    synthetic 5 s mono chunk (16 kHz)
    manifest.json              what is in each .f64 file
    *.f64                      raw little-endian float64 arrays

Goldens cover: conditioner outputs (mel+log+proj+mask, class id→row mapping
including the upstream +2 shift and row-1 null), full-forward logits (plain
and CFG-doubled), per-step incremental logits under the KV cache, greedy token
streams (forbidden-token masking + EOS), tie-prologue prompt generation, and
beam search output.

Regenerate with: MUSCRIPTOR_ROOT=/path/to/checkout python tools/gen_model_fixtures.py
Requires the upstream checkout and its Python dependencies, including torch and einops.
"""

import json
import os
import struct
import sys
from pathlib import Path

if os.environ.get("MUSCRIPTOR_ROOT"):
    sys.path.insert(0, os.environ["MUSCRIPTOR_ROOT"])

import numpy as np
import torch

torch.manual_seed(1234)

from muscriptor.modules.conditioners import (  # noqa: E402
    ClassConditioner,
    ConditioningAttributes,
    ConditioningProvider,
    MelSpectrogramConditioner,
    WavCondition,
    nullify_all_conditions,
)
from muscriptor.modules.streaming import increment_steps, init_states  # noqa: E402
from muscriptor.lm import LMModel  # noqa: E402

# ---- tiny config ----------------------------------------------------------
D = 32
HEADS = 4
LAYERS = 2
CARD = 1395  # medium's card: exercises the hardcoded logits[:, 1393:] mask
DIM_FF = 4 * D
SR = 16000
SEG = 80000  # 5 s chunk
EOS = 1
BOS = CARD  # initial_token_id
VOCAB_MT3 = 1393  # upstream masks logits[1393:] even though card=1395

FIX = Path(__file__).resolve().parent.parent / "crates/mtab-core/tests/fixtures/model"
FIX.mkdir(parents=True, exist_ok=True)

manifest = {"tensors": {}, "notes": "generated by tools/gen_model_fixtures.py"}


def save_f64(name: str, arr: torch.Tensor) -> None:
    a = arr.detach().cpu().to(torch.float64).numpy().astype("<f8")
    a.tofile(FIX / f"{name}.f64")
    manifest["tensors"][name] = {"file": f"{name}.f64", "shape": list(a.shape)}


def save_safetensors(path: Path, tensors: dict) -> None:
    header = {}
    offset = 0
    blob = b""
    for name, t in tensors.items():
        arr = t.detach().cpu().to(torch.float32).numpy().astype("<f4")
        raw = arr.tobytes()
        header[name] = {
            "dtype": "F32",
            "shape": list(arr.shape),
            "data_offsets": [offset, offset + len(raw)],
        }
        offset += len(raw)
        blob += raw
    h = json.dumps(header).encode()
    path.write_bytes(struct.pack("<Q", len(h)) + h + blob)


# ---- model ----------------------------------------------------------------
provider = ConditioningProvider(
    conditioners={
        "self_wav": MelSpectrogramConditioner(
            output_dim=D,
            device="cpu",
            sample_rate=SR,
            n_fft=2048,
            frame_rate=100,
            n_mel_bins=512,
            log_scale=True,
            eps=1e-6,
            normalize_audio=False,
        ),
        "instrument_group": ClassConditioner(1000, D),
        "dataset_name": ClassConditioner(4, D),
    }
)
model = LMModel(
    condition_provider=provider,
    card=CARD,
    dim=D,
    num_heads=HEADS,
    hidden_scale=4,
    cfg_coef=1.0,
    num_layers=LAYERS,
    max_period=10000,
)
model.eval()

# Weights are saved BEFORE .double(): goldens then compute in f64 from exactly
# the f32 values the Rust side loads (f32 → f64 is lossless).
save_safetensors(FIX / "tiny.fixture", model.state_dict())
model = model.double()

# ---- synthetic plucked-chord audio ----------------------------------------
t = torch.arange(SEG, dtype=torch.float64) / SR
g = torch.zeros(SEG, dtype=torch.float64)
for f0, amp, decay in [(196.0, 1.0, 1.2), (246.9, 0.7, 1.5), (293.7, 0.6, 1.8),
                       (392.0, 0.4, 2.2), (493.9, 0.25, 3.0)]:
    for h in range(1, 7):
        g += (amp / h) * torch.sin(2 * np.pi * f0 * h * t) * torch.exp(-decay * t)
g = 0.5 * g / g.abs().max()
wav = g.to(torch.float32).view(1, 1, SEG)  # upstream pipeline is f32 audio
wav.numpy().astype("<f4").tofile(FIX / "wav.f32")
manifest["tensors"]["wav"] = {"file": "wav.f32", "shape": [1, 1, SEG]}

# ---- conditions -----------------------------------------------------------
attrs = ConditioningAttributes(
    wav={
        "self_wav": WavCondition(
            wav=wav.double(),
            length=torch.tensor([SEG]),
            sample_rate=[SR],
            path=[None],
            seek_time=[0.0],
        )
    },
    text={"instrument_group": "4 5 6", "dataset_name": None},
)
nulls = nullify_all_conditions([attrs])

with torch.no_grad():
    conds1 = provider(provider.tokenize([attrs]))  # cfg_coef == 1.0 path
    conds2 = provider(provider.tokenize([attrs] + nulls))  # CFG path

for k, (c, m) in conds1.items():
    save_f64(f"cond1_{k}", c)
for k, (c, m) in conds2.items():
    save_f64(f"cond2_{k}", c)

# ---- token sequences ------------------------------------------------------
# vocab layout (M3a): shift 3..1003, pitch 1004..1131, vel 1132..1133,
# tie 1134, program 1135..1264. Tie prologue for open (24,60),(26,64):
prompt = [1135 + 24, 1004 + 60, 1135 + 26, 1004 + 64, 1134]
seq = [[BOS] + prompt + [5, 300, 1134, 1390, 100, 200, 400, 1392]][:12]
seq = torch.tensor(seq, dtype=torch.long)
save_f64("seq", seq.double())  # ids, stored as f64 for a uniform loader
manifest["tensors"]["seq"]["ids"] = seq[0].tolist()
manifest["tensors"]["prompt"] = {"ids": prompt}

# ---- full-forward logits + per-layer hidden captures ----------------------
with torch.no_grad():
    logits_full = model(seq, conds1, first_step=True)  # (1, T, CARD)
save_f64("logits_full", logits_full)

with torch.no_grad():
    doubled = torch.cat([seq, seq], dim=0)
    all_cfg = model(doubled, conds2, first_step=True)  # (2, 12, CARD)
save_f64("logits_cfg_all", all_cfg)
cfg_coef = 1.5
mixed_last = all_cfg[1, -1] + (all_cfg[0, -1] - all_cfg[1, -1]) * cfg_coef
save_f64("logits_cfg_mixed_last", mixed_last)
manifest["cfg_coef"] = cfg_coef

# ---- incremental decode under the KV cache --------------------------------
forbidden = [2, 1000, 1135]
manifest["forbidden"] = forbidden


def manual_greedy(prompt_ids, conds, cfg, max_gen_len=24):
    """Mirror LMModel.generate's beam_size==1 greedy branch; returns
    (all yielded tokens incl. prompt and EOS, per-step logits)."""
    prep = sum(c.shape[1] for c, _ in conds.values())
    cache_b = 1 if cfg == 1.0 else 2
    state = init_states(model, batch_size=cache_b, sequence_length=prep + max_gen_len)
    gen = torch.full((1, max_gen_len + 1), -2, dtype=torch.long)
    gen[:, 0] = BOS
    start = 0
    if prompt_ids:
        PT = len(prompt_ids)
        gen[:, 1 : 1 + PT] = torch.tensor([prompt_ids], dtype=torch.long)
        start = PT
    yielded = list(prompt_ids)
    step_logits = []
    for offset in range(start, max_gen_len):
        first = offset == start
        input_ = gen[:, : offset + 1] if first else gen[:, offset : offset + 1]
        with torch.no_grad():
            logits = model._compute_logits(
                input_, conds, state, first, cfg, forbidden_tokens=forbidden
            )
        step_logits.append(logits[0].clone())
        nxt = int(logits.argmax(dim=-1)[0])
        increment_steps(
            model.transformer,
            state,
            increment=input_.shape[-1] + (prep if first else 0),
        )
        gen[:, offset + 1] = nxt
        yielded.append(nxt)
        if nxt == EOS:
            break
    return yielded, step_logits


toks1, steps1 = manual_greedy([], conds1, 1.0)
save_f64("inc_step_logits", torch.stack(steps1))
save_f64("inc_tokens", torch.tensor(toks1, dtype=torch.float64))
manifest["tensors"]["inc_tokens"]["ids"] = toks1
manifest["tensors"]["inc_step_logits"]["note"] = "one (CARD,) row per generated step"

toks2, steps2 = manual_greedy(prompt, conds2, 1.5)
save_f64("inc_cfg_step_logits", torch.stack(steps2))
save_f64("inc_cfg_tokens", torch.tensor(toks2, dtype=torch.float64))
manifest["tensors"]["inc_cfg_tokens"]["ids"] = toks2

# Cross-check: upstream generate() must emit exactly the same greedy stream.
with torch.no_grad():
    gen1 = [
        int(x[0])
        for x in model.generate(
            prompt=None, conditions=[attrs], max_gen_len=24, use_sampling=False,
            cfg_coef=1.0, early_stop_on_token=EOS, forbidden_tokens=forbidden,
        )
    ]
assert gen1 == toks1, (gen1, toks1)
with torch.no_grad():
    gen2 = [
        int(x[0])
        for x in model.generate(
            prompt=torch.tensor([prompt], dtype=torch.long), conditions=[attrs],
            max_gen_len=24, use_sampling=False, cfg_coef=1.5,
            early_stop_on_token=EOS, forbidden_tokens=forbidden,
        )
    ]
assert gen2 == toks2, (gen2, toks2)

# ---- beam search ----------------------------------------------------------
with torch.no_grad():
    beam = [
        int(x[0])
        for x in model.generate(
            prompt=None, conditions=[attrs], max_gen_len=24, use_sampling=False,
            cfg_coef=1.0, early_stop_on_token=EOS, beam_size=2,
            forbidden_tokens=forbidden,
        )
    ]
save_f64("beam_tokens", torch.tensor(beam, dtype=torch.float64))
manifest["tensors"]["beam_tokens"]["ids"] = beam

# ---- sanity on golden quality --------------------------------------------
with torch.no_grad():
    top2 = torch.topk(logits_full[0, -1], 2).values
margin = float(top2[0] - top2[1])
manifest["min_top2_margin"] = margin
assert margin > 1e-3, f"argmax margin too small for stable token parity: {margin}"

(FIX / "manifest.json").write_text(json.dumps(manifest, indent=1))
print(f"OK: wrote fixtures to {FIX}")
print(f"  logits_full {tuple(logits_full.shape)}; inc steps {len(steps1)}; "
      f"cfg steps {len(steps2)}; beam {len(beam)} tokens; margin {margin:.4f}")
print("  greedy1:", toks1)
print("  greedy2:", toks2)
print("  beam:   ", beam)
